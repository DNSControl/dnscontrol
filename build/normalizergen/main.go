// Command normalizergen generates models/rdata_normalize.go from the RDATA
// field classifications. Run it with go generate ./models/.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"reflect"

	dnsv2 "codeberg.org/miekg/dns"
	"github.com/DNSControl/dnscontrol/v5/pkg/privatetypes"
	"github.com/DNSControl/dnscontrol/v5/pkg/rdatafields"
)

func main() {
	src, err := generate()
	if err != nil {
		log.Fatal(err)
	}
	const outputFile = "rdata_normalize.go"
	if err := os.WriteFile(outputFile, src, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("normalizergen: wrote %s\n", outputFile)
}

func generate() ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString(`// Code generated by normalizergen; DO NOT EDIT.

package models

import (
	"slices"
	"strings"

	dnsrdatav2 "codeberg.org/miekg/dns/rdata"
	privatetypesrdata "github.com/DNSControl/dnscontrol/v5/pkg/privatetypes/rdata"
)

// normalizeRDATA canonicalizes hostname and hex fields in rc.rdata for comparison.
// Constructors resolve relative hostnames before SetRDATA calls this method.
// Hostnames are already ASCII: makers convert IDNA, and provider imports supply ASCII.
// Mailboxes, opaque names, and unclassified fields are preserved.
func (rc *RecordConfig) normalizeRDATA() {
	switch v := rc.rdata.(type) {
	case dnsrdatav2.TXT:
		if !txtProperlySegmented(v.Txt) {
			v.Txt = TXTSegmented(v)
			rc.rdata = v
		}
`)

	// Several RR types share an RDATA struct (for example HTTPS and SVCB).
	seen := map[reflect.Type]bool{}
	for _, name := range privatetypes.GetAllTypeNames() {
		newFn, ok := dnsv2.TypeToRR[dnsv2.StringToType[name]]
		if !ok {
			continue
		}
		rd := newFn().Data()
		rt := reflect.TypeOf(rd)
		if rt == nil || rt.Kind() != reflect.Struct || seen[rt] {
			continue
		}
		seen[rt] = true

		var body bytes.Buffer
		for _, field := range rdatafields.Fields(rd) {
			switch field.Kind {
			case rdatafields.KindTargetHost, rdatafields.KindHexLower:
			default:
				continue
			}
			ft := rt.Field(field.Index).Type
			if field.Slice {
				ft = ft.Elem()
			}
			if ft.Kind() != reflect.String {
				return nil, fmt.Errorf("%s.%s: expected string or []string, got %s", rt, field.Name, rt.Field(field.Index).Type)
			}
			if field.Slice {
				// Clone each slice only on its first change, preserving the caller's input.
				fmt.Fprintf(&body, `		cloned%[1]s := false
		for i, value := range v.%[1]s {
			if normalized := strings.ToLower(value); normalized != value {
				if !cloned%[1]s {
					v.%[1]s = slices.Clone(v.%[1]s)
					cloned%[1]s = true
				}
				v.%[1]s[i] = normalized
			}
		}
		if cloned%[1]s {
			rc.rdata = v
		}
`, field.Name)
			} else {
				fmt.Fprintf(&body, `		if normalized := strings.ToLower(v.%[1]s); normalized != v.%[1]s {
			v.%[1]s = normalized
			rc.rdata = v
		}
`, field.Name)
			}
		}
		if body.Len() == 0 {
			continue
		}

		var pkg string
		switch rt.PkgPath() {
		case "codeberg.org/miekg/dns/rdata":
			pkg = "dnsrdatav2"
		case "github.com/DNSControl/dnscontrol/v5/pkg/privatetypes/rdata":
			pkg = "privatetypesrdata"
		default:
			return nil, fmt.Errorf("unsupported RDATA package: %s", rt.PkgPath())
		}
		fmt.Fprintf(&buf, "\tcase %s.%s:\n%s", pkg, rt.Name(), body.String())
	}
	buf.WriteString("\t}\n}\n")
	return format.Source(buf.Bytes())
}

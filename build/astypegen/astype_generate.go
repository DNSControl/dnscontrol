package main

// Command astype_generate generates models/record_astype.go.
//
// Generates an As$TYPE() method for every rtype.
//
// Run by `go generate ./models/` (see the //go:generate directive in rdata.go)
// and by bin/generate-all.sh.

import (
	"bytes"
	"fmt"
	"log"

	dnsv2 "codeberg.org/miekg/dns"
	"github.com/DNSControl/dnscontrol/v5/pkg/privatetypes"
)

const outputFile = "record_astype.go"

func main() {
	var buf bytes.Buffer

	buf.WriteString("// Code generated by astype_generate.go; DO NOT EDIT.\n\n")
	buf.WriteString("package models\n\n")
	buf.WriteString("import (\n")
	buf.WriteString("\tdnsrdatav2 \"codeberg.org/miekg/dns/rdata\"\n")
	buf.WriteString("\tprivatetypesrdata \"github.com/DNSControl/dnscontrol/v5/pkg/privatetypes/rdata\"\n")
	buf.WriteString(")\n\n")

	seen := map[string]bool{}
	for _, name := range privatetypes.GetAllTypeNames() {
		codepoint := dnsv2.StringToType[name]

		// Skip irrelevant rtypes. Make a struct of that type.
		newFn, ok := dnsv2.TypeToRR[codepoint]
		if !ok {
			continue
		}
		rd := newFn().Data()

		// is this a dnsrdatav2. or privatetypes. namespace?
		structName, pkgPath := StructName(rd)
		pkg, ok := Namespace(pkgPath)
		if structName == "" || !ok {
			continue
		}

		method := "As" + goIdent(name)
		// Have we seen this before?
		if seen[method] {
			continue
		}
		seen[method] = true

		fmt.Fprintf(&buf,
			"func (rc *RecordConfig) %s() %s.%s {\n\treturn rc.GetRDATA().(%s.%s)\n}\n\n",
			method, pkg, structName, pkg, structName)
	}

	if err := writeGoFile(outputFile, buf.Bytes()); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("astype_generate.go: wrote %s\n", outputFile)
}
